def export():
    ASSETS.mkdir(parents=True, exist_ok=True)
    paint_birds(ASSETS)
    tiles = blank(4 * 32, 3 * 32)
    pictures = [carrot, snail, ladybug, butterfly, fried_egg, mushroom,
                feather, apple, sunflower, strawberry, nest, corn]
    for index, picture in enumerate(pictures):
        tile = blank(32)
        picture(ImageDraw.Draw(tile))
        tiles.paste(tile, (index % 4 * 32, index // 4 * 32))
    tiles.save(ASSETS / "yard-icons.png", optimize=True)
    paint_field(ASSETS)


if __name__ == "__main__":
    export()
